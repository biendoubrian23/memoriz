/** Create a Fabric object ready to hold an image (mask) */
export function createClipFrame(
  canvas: fabric.Canvas,
  preset: ClipFramePreset
): fabric.FabricObject {
  // Use a Path object. We translate/scale it so it centers at origin (0,0) with a default size
  const pathObj = new fabric.Path(preset.svgPath, {
    fill: "#e5e7eb", // Light gray placeholder
    stroke: "#9ca3af",
    strokeWidth: 2,
    strokeDashArray: [5, 5], // Indicates it's an empty frame
    name: preset.name,
    objectCaching: false,
  });

  // Calculate generic bounding box and scale to a reasonable ~200px size
  const bbox = pathObj.getBoundingRect();
  const maxDim = Math.max(bbox.width, bbox.height);
  const scale = 200 / (maxDim || 200);

  const left = canvas.getWidth() / 2 - (bbox.width * scale) / 2;
  const top = canvas.getHeight() / 2 - (bbox.height * scale) / 2;

  pathObj.set({
    scaleX: scale,
    scaleY: scale,
    left,
    top,
  });

  // Tag it so our drop logic knows it's an image container
  (pathObj as any).isImageFrame = true;
  (pathObj as any).originalFrameId = preset.id;

  // If there are visual overlays, we should group them so they are draggable together
  if (preset.overlayPaths && preset.overlayPaths.length > 0) {
    const objects: fabric.FabricObject[] = [pathObj];

    for (const d of preset.overlayPaths) {
      const decPath = new fabric.Path(d.path, {
        fill: d.fill || "",
        stroke: d.stroke || "",
        strokeWidth: d.strokeWidth || 0,
        scaleX: scale,
        scaleY: scale,
        left,
        top,
        objectCaching: false,
      });
      objects.push(decPath);
    }

    const group = new fabric.Group(objects, {
      name: preset.name,
    });

    // Pass along the crucial tags to the proxy group
    (group as any).isImageFrame = true;
    (group as any).originalFrameId = preset.id;
    return group;
  }

  return pathObj;
}
